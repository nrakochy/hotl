/// The optional opening prompt for `hotl bg`: the first non-flag arg that is
/// not a flag's value. `-w`'s value is optional, so a non-flag token right
/// after it is its name — put the prompt first, or name the branch.
fn bg_prompt(args: &[String]) -> Option<&str> {
    let mut it = args.iter().skip(1).peekable();
    while let Some(a) = it.next() {
        match a.as_str() {
            "-n" | "--name" => {
                it.next(); // skip the flag's value
            }
            "-w" | "--worktree" => {
                if it.peek().is_some_and(|v| !v.starts_with('-')) {
                    it.next();
                }
            }
            s if !s.starts_with('-') => return Some(s),
            _ => {}
        }
    }
    None
}

/// The `-w`/`--worktree [name]` request for `hotl bg` (0065).
fn bg_worktree(args: &[String]) -> Option<tui::WorktreeArg> {
    let mut it = args.iter().skip(1).peekable();
    while let Some(a) = it.next() {
        if matches!(a.as_str(), "-w" | "--worktree") {
            return Some(match it.peek() {
                Some(v) if !v.starts_with('-') => tui::WorktreeArg::Named((*v).clone()),
                _ => tui::WorktreeArg::Derived,
            });
        }
    }
    None
}

/// The `-n`/`--name` value for `hotl bg`, normalized.
fn bg_name(args: &[String]) -> Option<String> {
    let mut it = args.iter().skip(1);
    while let Some(a) = it.next() {
        if matches!(a.as_str(), "-n" | "--name") {
            return it
                .next()
                .and_then(|v| hotl_types::normalize_session_name(v));
        }
    }
    None
}

/// What `hotl serve` was started with: `--id <id>`, `--prompt <p>`,
/// `--name <n>`, `--worktree <name|@derived>` (0065). A missing id is
/// generated.
struct ServeArgs {
    id: String,
    prompt: Option<String>,
    name: Option<String>,
    worktree: Option<tui::WorktreeArg>,
}

fn parse_serve_args(args: &[String]) -> ServeArgs {
    let mut id = None;
    let mut prompt = None;
    let mut name = None;
    let mut worktree = None;
    let mut it = args.iter().skip(1);
    while let Some(a) = it.next() {
        match a.as_str() {
            "--id" => id = it.next().cloned(),
            "--prompt" => prompt = it.next().cloned(),
            "--name" => name = it.next().cloned(),
            // Always spelled on the wire: `@derived` is a request, an absent
            // flag is none.
            "--worktree" => worktree = it.next().map(|w| tui::WorktreeArg::from_wire(w)),
            _ => {}
        }
    }
    ServeArgs {
        id: id.unwrap_or_else(|| format!("bg-{}", std::process::id())),
        prompt,
        name,
        worktree,
    }
}

/// One-shot CLI paths run current_thread per the async policy (no pool
/// spinup on the cold-start path). `[concurrency].blocking_threads` sizes
/// the *blocking* pool (`.max_blocking_threads`) on this same
/// `current_thread` builder — that call is valid on any runtime flavor
/// (unlike `.worker_threads()`, which only applies to `multi_thread` and
/// stays deliberately inert; see `agent::layer_c_warning`) and is the one
/// Layer-C lever that actually matters here: it bounds both real
/// blocking-pool users in hotl today — `glob`'s `spawn_blocking` tree walk
/// and `tui::load_image`'s decode-plus-base64 work. Read once, synchronously,
/// before the runtime exists — config loading itself needs no async.
fn block_on(f: impl std::future::Future<Output = i32>) -> i32 {
    // Warm the sandbox floor probe (a real confined-canary spawn, OnceLock-
    // memoized) so its ~100ms overlaps startup instead of serializing inside
    // scaffold(). Reads only HOTL_SANDBOX from the env — safe this early;
    // `OnceLock::get_or_init` blocks any concurrent second caller until this
    // first one finishes, so existing call sites only ever observe *earlier*
    // answers (0033 Task 8c).
    std::thread::spawn(hotl_tools::sandbox::probe);
    let mut builder = tokio::runtime::Builder::new_current_thread();
    builder.enable_all();
    if let Some(n) = resolve_blocking_threads() {
        builder.max_blocking_threads(n);
    }
    let runtime = builder.build().expect("tokio runtime");
    let code = runtime.block_on(f);
    // Bounded, not `Drop`: dropping the runtime waits forever for running
    // blocking-pool tasks, and `drain_capped_blocking` strands one whenever a
    // bash descendant escapes its process group and keeps the output pipe
    // open (the trade builtins.rs states). By now the terminal guard has
    // already restored the screen, so that wait reads as "ctrl-c exited the
    // TUI but the process is still here" until a second ctrl-c — a real
    // SIGINT once raw mode is off — ends it. Pending async tasks are still
    // dropped (session-log flush included); only stuck blocking threads are
    // abandoned, and `main` exits the process right after.
    runtime.shutdown_timeout(std::time::Duration::from_millis(500));
    code
}

/// `[concurrency].blocking_threads` (env `HOTL_CONCURRENCY_BLOCKING_THREADS`
/// wins over config.toml), reusing the exact same env-over-config precedence
/// `agent::layer_c_resolved` already implements. `None` = the owner never
/// set it — leave tokio's own default (512) alone. `Some(0)` (an explicit,
/// degenerate override) is clamped to 1: a 0-thread blocking pool would hang
/// every `spawn_blocking` caller forever, which is worse than ignoring a
/// nonsensical value — the same "never deadlock the budget" stance
/// `SessionConcurrency` takes for its own zero-limit case.
fn resolve_blocking_threads() -> Option<usize> {
    let secrets = hotl_platform::EnvSecrets;
    let cfg = crate::config::Config::load(&agent::config_dir());
    let (_worker_threads, blocking_threads) = agent::layer_c_resolved(&secrets, &cfg.concurrency);
    blocking_threads.map(|n| n.max(1))
}

