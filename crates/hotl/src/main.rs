    /// String-level: the rewrite branch marks itself, preexec carries the
    /// mark into `_hotl_last_was_hotl`, and the capture checks it first.
    #[test]
    fn zsh_plugin_skips_capture_when_the_last_command_was_hotl() {
        let p = super::ZSH_PLUGIN;
        let rewrite = p
            .find("_hotl_rewrote=1")
            .expect("the rewrite branch marks itself");
        let accept = p.find("hotl-accept-line() {").unwrap();
        let accept_end = p[accept..].find("\n}\n").unwrap() + accept;
        assert!(
            accept < rewrite && rewrite < accept_end,
            "the mark is set inside accept-line"
        );
        assert!(p.contains("_hotl_last_was_hotl=$_hotl_rewrote"));
        assert!(
            p.contains("-z $_hotl_last_was_hotl"),
            "capture is gated on the mark"
        );
        // The command line never passes through prompt expansion.
        assert!(!p.contains("print -P \"$1\"") && !p.contains("print -Pn \"$_hotl_last_cmd"));
        // `$?` is the first thing precmd reads.
        let precmd = p.find("hotl-precmd() {").unwrap();
        assert!(p[precmd..]
            .trim_start_matches("hotl-precmd() {")
            .trim_start()
            .starts_with("local st=$?"));
        assert!(super::init_script("bash")
            .unwrap()
            .contains("complete -F _hotl hotl"));
        assert!(super::init_script("fish")
            .unwrap()
            .contains("complete -c hotl"));
        assert!(super::init_script("powershell").is_none());
    }

