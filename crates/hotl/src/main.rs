/// The zsh `:` prefix: a line starting with `: ` becomes
/// an agent prompt; everything else runs as normal shell.
const ZSH_PLUGIN: &str = r#"# hotl zsh plugin — generated by `hotl init zsh`
# A command line starting with `: ` becomes an agent prompt (hotl -p).
# `@[path]` tokens in that prompt are expanded to the file's contents by hotl.
# The last command, its exit status, its duration and (in tmux) its output ride
# along as --shell-trace; HOTL_SHELL_TRACE=0 turns that off. HOTL_TRACE_LINES
# (200) bounds the capture, HOTL_TRACE_MAX_AGE (1800 s) its age,
# HOTL_PROMPT_LINES (1) is the height of your prompt.
zmodload zsh/datetime 2>/dev/null
typeset -g _hotl_last_cmd _hotl_last_was_hotl _hotl_rewrote _hotl_t0 _hotl_cmd_at
typeset -g _hotl_status _hotl_ms _hotl_start

hotl-trace-write() {
  local f
  f=$(umask 077; mktemp "${TMPDIR:-/tmp}/hotl-trace.XXXXXX") || return 1
  {
    print -r -- "cmd=$_hotl_last_cmd"
    print -r -- "exit=$_hotl_status"
    print -r -- "ms=$_hotl_ms"
    print -r -- "cwd=$PWD"
    if [[ -n $TMUX_PANE && -n $_hotl_start ]]; then
      # The start is history_size:cursor_y recorded at preexec; the end is the
      # row above this prompt, read now (one tmux call per command, not two —
      # measured 3.4 ms each). The pane may have scrolled since preexec, so the
      # start is converted to an offset from the current history size.
      local now=$(tmux display -p -t "$TMUX_PANE" '#{history_size}:#{cursor_y}' 2>/dev/null)
      local now_hist=${now%%:*} cur_y=${now##*:}
      now_hist=${now_hist:-0}; cur_y=${cur_y:-0}
      local s_hist=${_hotl_start%%:*} s_y=${_hotl_start##*:}
      local start=$(( s_hist + s_y - now_hist ))
      local end=$(( cur_y - ${HOTL_PROMPT_LINES:-1} ))
      local captured=tmux
      if (( start < -now_hist )); then captured='tmux(partial)'; start=$(( -now_hist )); fi
      if (( end < start )); then end=$start; fi
      print -r -- "captured=$captured"
      print -r -- "---"
      tmux capture-pane -p -J -t "$TMUX_PANE" -S $start -E $end 2>/dev/null | tail -n ${HOTL_TRACE_LINES:-200}
    else
      print -r -- "captured=none"
      print -r -- "---"
    fi
  } > "$f"
  print -r -- "$f"
}

hotl-accept-line() {
  if [[ $BUFFER == ':'\ * ]]; then
    local prompt_text=${BUFFER#: }
    local trace_file=
    if [[ ${HOTL_SHELL_TRACE:-1} != 0 && -n $_hotl_last_cmd && -z $_hotl_last_was_hotl ]] \
       && (( EPOCHSECONDS - ${_hotl_cmd_at:-0} <= ${HOTL_TRACE_MAX_AGE:-1800} )); then
      trace_file=$(hotl-trace-write)
    fi
    if [[ -n $trace_file ]]; then
      BUFFER="hotl -p ${(qq)prompt_text} --shell-trace ${(qq)trace_file}"
    else
      BUFFER="hotl -p ${(qq)prompt_text}"
    fi
    # The rewritten line is the next command preexec sees: mark it so the
    # following `: ` does not attach hotl's own output as a trace.
    _hotl_rewrote=1
  fi
  zle .accept-line
}
zle -N accept-line hotl-accept-line

# OSC-133 shell integration: mark prompt/command/output regions so a terminal
# (and `hotl watch`) can find prompts and command boundaries in the scrollback.
# `$?` is read on the first line, before anything else can replace it.
hotl-precmd() {
  local st=$?
  print -Pn "\e]133;D;$st\a\e]133;A\a"
  [[ ${HOTL_SHELL_TRACE:-1} == 0 ]] && return
  if [[ -n $_hotl_t0 ]]; then
    _hotl_status=$st
    _hotl_ms=$(( (EPOCHREALTIME - _hotl_t0) * 1000 ))
    _hotl_ms=${_hotl_ms%.*}
    _hotl_t0=
  fi
}
hotl-preexec() {
  print -Pn "\e]133;C\a"
  [[ ${HOTL_SHELL_TRACE:-1} == 0 ]] && return
  # The command line never goes through `-P`: a `%` in it must not expand.
  _hotl_last_cmd=$1
  _hotl_last_was_hotl=$_hotl_rewrote
  _hotl_rewrote=
  _hotl_t0=$EPOCHREALTIME
  _hotl_cmd_at=$EPOCHSECONDS
  _hotl_start=
  [[ -n $TMUX_PANE ]] && _hotl_start=$(tmux display -p -t "$TMUX_PANE" '#{history_size}:#{cursor_y}' 2>/dev/null)
}
autoload -Uz add-zsh-hook
add-zsh-hook precmd  hotl-precmd
add-zsh-hook preexec hotl-preexec
"#;

