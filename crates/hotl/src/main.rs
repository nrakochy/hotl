/// `hotl init <shell>`: zsh gets the `:` prefix plugin and completion in one
/// eval; bash and fish get completion only.
fn init_script(shell: &str) -> Option<String> {
    match shell {
        "zsh" => Some(format!("{ZSH_PLUGIN}\n{ZSH_COMPLETION}")),
        "bash" => Some(BASH_COMPLETION.to_string()),
        "fish" => Some(FISH_COMPLETION.to_string()),
        _ => None,
    }
}

/// `hotl __sessions`: `id<TAB>name` per line, newest first, 20 rows — what
/// the completion scripts read after `-r`, `--resume`, `--fork-from`, `export`.
fn print_sessions_for_completion() {
    let dir = agent::sessions_dir();
    for (id, path, _) in agent::sessions_newest_first(&dir).into_iter().take(20) {
        let name = hotl_store::session_name(&path).unwrap_or_default();
        println!("{id}\t{name}");
    }
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match args.first().map(String::as_str) {
        Some("watch") => {
            if let Err(e) = watch::watch_main() {
                eprintln!("hotl watch: {e}");
                std::process::exit(1);
            }
        }
        Some("fleet") => {
            eprintln!("hotl fleet (orchestrate) is reserved and not built yet — it arrives after the harness's M4 seams.");
            std::process::exit(2);
        }
        Some("doctor") => std::process::exit(doctor::doctor_main()),
        Some("resume") => {
            let mut rest = vec!["--resume".to_string()];
            rest.extend(args[1..].iter().cloned());
            // `hotl resume <s> -p "…"` is the headless resume, not the console's.
            if is_headless(&rest) {
                std::process::exit(block_on(agent::agent_main(rest)));
            }
            std::process::exit(block_on(tui::tui_main(rest)));
        }
        Some("acp") => std::process::exit(block_on(agent::acp_main())),
        Some("bg") => std::process::exit(bg::bg_main(
            bg_prompt(&args),
            bg_name(&args).as_deref(),
            bg_worktree(&args).as_ref(),
        )),
        Some("attach") => std::process::exit(block_on(attach::attach_main(
            args.get(1).map(String::as_str),
        ))),
        Some("approve") => std::process::exit(block_on(approve_cli::approve_main(&args[1..]))),
        Some("serve") => {
            let ServeArgs {
                id,
                prompt,
                name,
                worktree,
            } = parse_serve_args(&args);
            std::process::exit(block_on(agent::serve_main(id, prompt, name, worktree)));
        }
        Some("setup") => {
            let force = args.iter().any(|a| a == "--force" || a == "-f");
            std::process::exit(setup::setup_main(&agent::config_dir(), force));
        }
        Some("gc") => std::process::exit(gc::gc_main(&args)),
        Some("export") => std::process::exit(export::export_main(&args[1..])),
        Some("stats") => std::process::exit(stats::stats_main(&args[1..])),
        Some("schema") => std::process::exit(schema_cli::schema_main(&args[1..])),
        Some("mcp") => std::process::exit(mcp_cli::mcp_main(&args)),
        Some("plugins") => std::process::exit(plugins_cli::plugins_main(&args)),
        Some("skills") => std::process::exit(skills_cli::skills_main(&args)),
        Some("workflows") => std::process::exit(workflows_cli::workflows_main(&args)),
        Some("update") => std::process::exit(block_on(update::update_main(&args, &version_line()))),
        Some("init") => {
            // Binary-generated shell integration: the zsh `:` prefix plugin
            // plus completion; completion alone for bash and fish.
            match args.get(1).map(String::as_str).and_then(init_script) {
                Some(script) => print!("{script}"),
                None => {
                    eprintln!(
                        "usage: hotl init zsh|bash|fish   # then: eval \"$(hotl init zsh)\" in \
                         ~/.zshrc (no PowerShell completion yet)"
                    );
                    std::process::exit(2);
                }
            }
        }
        Some("__sessions") => print_sessions_for_completion(),
        Some("--help") | Some("-h") | Some("help") => print_help(),
        Some("--version") | Some("-V") | Some("version") => print_version(),
        _ => {
            if is_headless(&args) {
                std::process::exit(block_on(agent::agent_main(args)));
            }
            std::process::exit(block_on(tui::tui_main(args)));
        }
    }
}

/// Headless flags route to `agent.rs`; everything else in the catch-all is
/// the TUI's (bare, an id-prefix, or --resume).
fn is_headless(args: &[String]) -> bool {
    args.iter().any(|a| {
        matches!(
            a.as_str(),
            "-p" | "--print" | "--json" | "--json-schema" | "--goal"
        )
    })
}

